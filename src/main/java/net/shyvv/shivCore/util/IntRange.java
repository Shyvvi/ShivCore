package net.shyvv.shivCore.util;

public class IntRange {
    int firstInt;
    int secondInt;
    public IntRange(int firstInt, int secondInt) {
        this.firstInt = firstInt;
        this.secondInt = secondInt;
    }

    public int getFirstInt() {
        return firstInt;
    }

    public int getSecondInt() {
        return secondInt;
    }
}
